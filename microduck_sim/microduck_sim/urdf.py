"""MJCF -> URDF for robot_state_publisher, generated from the compiled MuJoCo model.

Kinematics come straight from MuJoCo (body_pos/body_quat relative to the parent,
jnt_axis, jnt_range), so the TF tree matches the simulation exactly; a test checks
forward kinematics link by link. Visual meshes point at the original STL files
(file://), with MuJoCo's mesh recentring undone. Sites and cameras become fixed
child links (imu, tof, feet, head_camera + head_camera_optical_frame).

  ros2 run microduck_sim make_urdf --scene flat > microduck.urdf
"""

import argparse
import os
import sys
from xml.sax.saxutils import quoteattr

import mujoco
import numpy as np

from .engine import SCENE_DIR_REL, SCENES, TRUNK_BODY, load_scene_spec


def _rpy(R):
    """URDF rpy (fixed-axis XYZ: R = Rz(yaw) Ry(pitch) Rx(roll)) from a rotation matrix."""
    sy = -R[2, 0]
    if abs(sy) < 1.0 - 1e-9:
        pitch = np.arcsin(sy)
        roll = np.arctan2(R[2, 1], R[2, 2])
        yaw = np.arctan2(R[1, 0], R[0, 0])
    else:  # gimbal lock
        pitch = np.pi / 2 * np.sign(sy)
        roll = 0.0
        yaw = np.arctan2(-R[0, 1], R[1, 1])
    return roll, pitch, yaw


def _quat_mat(q):
    R = np.zeros(9)
    mujoco.mju_quat2Mat(R, np.asarray(q, dtype=np.float64))
    return R.reshape(3, 3)


def _origin(T):
    r, p, y = _rpy(T[:3, :3])
    x, yy, z = T[:3, 3]
    return f'<origin xyz="{x:.9g} {yy:.9g} {z:.9g}" rpy="{r:.9g} {p:.9g} {y:.9g}"/>'


def _T(pos, quat):
    T = np.eye(4)
    T[:3, :3] = _quat_mat(quat)
    T[:3, 3] = pos
    return T


# MuJoCo cameras look along -z with +y up; ROS optical frames look along +z with +y down.
T_CAM_TO_OPTICAL = np.diag([1.0, -1.0, -1.0, 1.0])


def mjcf_to_urdf(model, spec, base_dir, robot_name="microduck", root_body=TRUNK_BODY):
    m = model
    root = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, root_body)
    if root < 0:
        raise ValueError(f"no body '{root_body}'")
    bodies = [b for b in range(m.nbody) if m.body_rootid[b] == root]
    bname = lambda b: mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_BODY, b)  # noqa: E731

    meshdir = spec.meshdir or ""
    mesh_files = {}
    for mesh in spec.meshes:
        path = mesh.file
        if not os.path.isabs(path):
            path = os.path.normpath(os.path.join(base_dir, meshdir, path))
        mesh_files[mesh.name] = path

    out = [f'<?xml version="1.0"?>\n<robot name="{robot_name}">',
           "  <!-- Generated by microduck_sim/urdf.py from the MuJoCo model. Do not edit. -->"]
    names = set()
    root_inertial = []

    for b in bodies:
        link = bname(b)
        names.add(link)
        out.append(f"  <link name={quoteattr(link)}>")
        mass = float(m.body_mass[b])
        inertial = ""
        if mass > 0:
            Ti = _T(m.body_ipos[b], m.body_iquat[b])
            ixx, iyy, izz = (float(v) for v in m.body_inertia[b])
            inertial = (f"<inertial>{_origin(Ti)}<mass value=\"{mass:.9g}\"/>"
                        f'<inertia ixx="{ixx:.9g}" ixy="0" ixz="0" iyy="{iyy:.9g}" iyz="0" izz="{izz:.9g}"/></inertial>')
        if inertial and b == root:
            # KDL ignores inertia on the root link, so it goes on a fixed child.
            root_inertial.append(inertial)
        elif inertial:
            out.append("    " + inertial)
        for g in range(m.ngeom):
            if m.geom_bodyid[g] != b or int(m.geom_type[g]) != int(mujoco.mjtGeom.mjGEOM_MESH):
                continue
            if m.geom_rgba[g][3] == 0.0 or m.geom_group[g] > 2:
                continue
            mid = int(m.geom_dataid[g])
            path = mesh_files.get(mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_MESH, mid))
            if not path or not os.path.isfile(path):
                continue
            # body <- geom <- original file (undo MuJoCo's recentring: v_mj = R^T (v_file - p))
            Rm = _quat_mat(m.mesh_quat[mid])
            T_geom_file = np.eye(4)
            T_geom_file[:3, :3] = Rm.T
            T_geom_file[:3, 3] = -Rm.T @ m.mesh_pos[mid]
            T = _T(m.geom_pos[g], m.geom_quat[g]) @ T_geom_file
            mat = int(m.geom_matid[g])
            rgba = m.mat_rgba[mat] if mat >= 0 else m.geom_rgba[g]
            out.append(f"    <visual>{_origin(T)}<geometry><mesh filename={quoteattr('file://' + path)}/></geometry>"
                       f'<material name="m{g}"><color rgba="{rgba[0]:.3g} {rgba[1]:.3g} {rgba[2]:.3g} {rgba[3]:.3g}"/>'
                       "</material></visual>")
        out.append("  </link>")

    if root_inertial:
        rname = bname(root)
        names.add(rname + "_inertia")
        out.append(f'  <link name="{rname}_inertia">{root_inertial[0]}</link>')
        out.append(f'  <joint name="{rname}_inertia_joint" type="fixed"><parent link="{rname}"/>'
                   f'<child link="{rname}_inertia"/><origin xyz="0 0 0" rpy="0 0 0"/></joint>')

    for b in bodies:
        if b == root:
            continue
        parent, child = bname(int(m.body_parentid[b])), bname(b)
        T = _T(m.body_pos[b], m.body_quat[b])
        jids = [j for j in range(m.njnt) if m.jnt_bodyid[j] == b]
        if len(jids) > 1:
            raise ValueError(f"body {child} has {len(jids)} joints; URDF supports one")
        if not jids:
            out.append(f'  <joint name="{child}_fixed" type="fixed"><parent link="{parent}"/>'
                       f'<child link="{child}"/>{_origin(T)}</joint>')
            continue
        j = jids[0]
        jtype = int(m.jnt_type[j])
        hinge, slide = int(mujoco.mjtJoint.mjJNT_HINGE), int(mujoco.mjtJoint.mjJNT_SLIDE)
        if jtype not in (hinge, slide):
            raise ValueError(f"joint type {jtype} on {child} not supported")
        if np.linalg.norm(m.jnt_pos[j]) > 1e-9:
            raise ValueError(f"joint on {child} is offset from its body origin; not supported")
        jname = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_JOINT, j)
        ax = m.jnt_axis[j]
        kind = "revolute" if jtype == hinge else "prismatic"
        lo, hi = (float(v) for v in m.jnt_range[j])
        if not m.jnt_limited[j]:
            lo, hi = (-np.pi, np.pi) if kind == "revolute" else (-1.0, 1.0)
            if kind == "revolute":
                kind = "continuous"
        limit = "" if kind == "continuous" else f'<limit lower="{lo:.9g}" upper="{hi:.9g}" effort="1.0" velocity="10.0"/>'
        out.append(f'  <joint name={quoteattr(jname)} type="{kind}"><parent link="{parent}"/>'
                   f'<child link="{child}"/>{_origin(T)}<axis xyz="{ax[0]:.9g} {ax[1]:.9g} {ax[2]:.9g}"/>'
                   f"{limit}</joint>")

    def fixed_frame(name, parent_body, T):
        if name in names:
            name = name + "_frame"
        names.add(name)
        out.append(f"  <link name={quoteattr(name)}/>")
        out.append(f'  <joint name={quoteattr(name + "_joint")} type="fixed"><parent link={quoteattr(bname(parent_body))}/>'
                   f"<child link={quoteattr(name)}/>{_origin(T)}</joint>")
        return name

    for s in range(m.nsite):
        b = int(m.site_bodyid[s])
        if b in bodies:
            fixed_frame(mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_SITE, s), b, _T(m.site_pos[s], m.site_quat[s]))
    for c in range(m.ncam):
        b = int(m.cam_bodyid[c])
        if b in bodies:
            cname = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_CAMERA, c)
            # the MuJoCo camera frame, then the ROS optical frame under it
            frame = fixed_frame(cname + "_mujoco", b, _T(m.cam_pos[c], m.cam_quat[c]))
            out.append(f"  <link name={quoteattr(cname + '_optical_frame')}/>")
            out.append(f'  <joint name={quoteattr(cname + "_optical_joint")} type="fixed"><parent link={quoteattr(frame)}/>'
                       f'<child link={quoteattr(cname + "_optical_frame")}/>{_origin(T_CAM_TO_OPTICAL)}</joint>')

    out.append("</robot>")
    return "\n".join(out) + "\n"


def urdf_for_scene(scene_path):
    spec = load_scene_spec(scene_path)
    model = spec.compile()
    return mjcf_to_urdf(model, spec, os.path.dirname(os.path.abspath(scene_path)))


def resolve_scene(scene, rl_path):
    if scene in SCENES:
        scene = os.path.join(SCENE_DIR_REL, SCENES[scene])
    if not os.path.isabs(scene):
        scene = os.path.join(os.path.expanduser(rl_path), scene)
    return scene


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the Microduck URDF (generated from the MuJoCo model).")
    ap.add_argument("--scene", default="flat")
    ap.add_argument("--microduck-rl-path",
                    default=os.environ.get("MICRODUCK_RL_PATH", os.path.expanduser("~/microduck_rl")))
    ap.add_argument("--out", default="-", help="file path, or - for stdout")
    a = ap.parse_args(argv)
    text = urdf_for_scene(resolve_scene(a.scene, a.microduck_rl_path))
    if a.out == "-":
        sys.stdout.write(text)
    else:
        with open(a.out, "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
